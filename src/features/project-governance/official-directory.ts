export function applyOfficialDirectory(d: Directory) {
  for (const old of [...d.units, ...d.positions, ...d.people]) old.sourceType = 'demo'
  for (const row of officialDirectorySnapshot) {
    const source = { sourceType: 'official' as const, sourceUrl: row.sourceUrl, observedAt: row.observedAt }
    const org = d.organizations.find(o => o.id === row.organizationId)
    if (row.organization) {
      if (org) Object.assign(org, row.organization, source)
      else d.organizations.push({ ...row.organization, active: true, ...source })
    } else if (org) Object.assign(org, source)
    let unit = d.units.find(u => u.id === row.unitId)
    if (!unit) {
      unit = { id: row.unitId, organizationId: row.organizationId, code: `SRC-${d.units.length+1}`, name: row.unitName, active: true }
      d.units.push(unit)
    }
    Object.assign(unit, { name: row.unitName, kind: row.unitKind, ...source, sourceType: 'derived' })
    d.positions.push({ id: row.positionId, organizationId: row.organizationId, unitId: row.unitId, code: `POS-${d.positions.length+1}`, name: row.position, roles: [], active: true, ...source })
    d.people.push({ id: row.personId, organizationId: row.organizationId, unitId: row.unitId, positionId: row.positionId, name: row.name, position: row.position, roles: [], active: true, phone: row.phone ?? undefined, email: row.email ?? undefined, ...source })
  }
}
